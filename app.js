function pad(n) {
  return String(n).padStart(2, "0");
}

function toDatetimeLocalValue(date) {
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function syncDateTimePartsFromHidden() {
  if (!quakeDateInput || !quakeClockInput) return;
  const value = quakeTimeInput.value;
  if (!value || !value.includes("T")) {
    quakeDateInput.value = "";
    quakeClockInput.value = "";
    return;
  }
  const [datePart, timePart] = value.split("T");
  quakeDateInput.value = datePart || "";
  quakeClockInput.value = (timePart || "").slice(0, 5);
}

function syncHiddenFromDateTimeParts() {
  if (!quakeDateInput || !quakeClockInput) return;
  if (quakeDateInput.value && quakeClockInput.value) {
    quakeTimeInput.value = `${quakeDateInput.value}T${quakeClockInput.value}`;
  } else {
    quakeTimeInput.value = "";
  }
}

function formatElapsed(minutes) {
  if (minutes < 0) return "未来の時刻です";
  if (minutes < 60) return `${minutes}分経過`;
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  if (h < 24) return `${h}時間${m > 0 ? m + "分" : ""}経過`;
  const d = Math.floor(h / 24);
  const rh = h % 24;
  return `${d}日${rh > 0 ? rh + "時間" : ""}経過`;
}

function formatRange(start, end) {
  return `${formatTimePoint(start)}〜${formatTimePoint(end)}`;
}

function formatTimePoint(min) {
  if (min < 60) return `${min}分`;
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (h < 24) return m === 0 ? `${h}時間` : `${h}時間${m}分`;
  const d = Math.floor(h / 24);
  const rh = h % 24;
  return rh === 0 ? `${d}日` : `${d}日${rh}時間`;
}

function getElapsedMinutes() {
  syncHiddenFromDateTimeParts();
  const value = quakeTimeInput.value;
  if (!value) return null;
  const quakeTime = new Date(value);
  if (Number.isNaN(quakeTime.getTime())) return null;
  return Math.floor((Date.now() - quakeTime.getTime()) / 60000);
}

function checksKey() {
  const role = roleSelect.value || "";
  const time = quakeTimeInput.value || "no-time";
  return `${STORAGE_PREFIX}:checks:${role}:${time}`;
}

function getChecks() {
  try {
    return JSON.parse(localStorage.getItem(checksKey()) || "{}");
  } catch {
    return {};
  }
}

function saveCheck(taskId, checked) {
  const checks = getChecks();
  checks[taskId] = checked;
  localStorage.setItem(checksKey(), JSON.stringify(checks));
}

function initRoleSelect() {
  roleSelect.innerHTML = roles.map(role => `<option value="${escapeHtml(role)}">${escapeHtml(role)}</option>`).join("");
  const savedRole = localStorage.getItem(`${STORAGE_PREFIX}:role`);
  roleSelect.value = savedRole && roles.includes(savedRole) ? savedRole : "住民";
}

function initQuakeTime() {
  const saved = localStorage.getItem(`${STORAGE_PREFIX}:quakeTime`);
  const savedAgo = localStorage.getItem(`${STORAGE_PREFIX}:selectedMinutesAgo`);
  if (saved) {
    quakeTimeInput.value = saved;
    selectedMinutesAgo = savedAgo === "manual" || savedAgo === null ? null : Number(savedAgo);
    if (Number.isNaN(selectedMinutesAgo)) selectedMinutesAgo = null;
  } else {
    selectedMinutesAgo = 0;
    quakeTimeInput.value = toDatetimeLocalValue(new Date());
  }
  syncDateTimePartsFromHidden();
}

function getRoleTasks() {
  return tasks
    .filter(task => task.role === roleSelect.value)
    .sort((a, b) => a.startMin - b.startMin || a.endMin - b.endMin || a.title.localeCompare(b.title, "ja"));
}

function statusForTask(task, elapsed, checked) {
  if (checked) return { label: "完了", className: "done" };
  if (elapsed === null || elapsed < task.startMin) return { label: "これから", className: "" };
  if (elapsed >= task.startMin && elapsed <= task.endMin) return { label: "今やる", className: "now" };
  return { label: "要確認", className: "overdue" };
}

